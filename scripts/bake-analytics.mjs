import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const outPath = resolve(__dirname, "../packages/shared/src/analytics/baked.ts");

const mode = process.argv[2] || "on";

const enabled = mode === "on";
const posthogApiKey = enabled ? "phc_REPLACE_WITH_REAL_KEY" : "";
const posthogHost = enabled ? "https://us.i.posthog.com" : "";
// A Sentry DSN is a public, write-only identifier. It already ships inside the
// browser bundle and the published image, so committing it here leaks nothing.
const sentryDsn = enabled
  ? "https://8bb088d82ba026d28c8936ec9292b009@o4511137467727872.ingest.us.sentry.io/4511137492238336"
  : "";
// tracesSampleRate only governs performance transactions; errors are always
// captured. Keep this low so fleet-wide tracing does not drain Sentry quota.
const sampleRate = enabled ? 0.1 : 0;

const content = `// AUTO-GENERATED by scripts/bake-analytics.mjs -- do not edit manually
export const ANALYTICS_BAKED = {
  enabled: ${enabled},
  posthogApiKey: "${posthogApiKey}",
  posthogHost: "${posthogHost}",
  sentryDsn: "${sentryDsn}",
  sampleRate: ${sampleRate},
} as const;
`;

writeFileSync(outPath, content, "utf-8");
console.log(`bake-analytics: wrote ${outPath} (mode=${mode}, enabled=${enabled})`);
